// Pulls every NBA team's game schedule from ESPN's public fantasy basketball API
// and writes it to data/schedule.js, so the site (and weekly lineup planning) can
// count how many games each player has in a matchup week.
//
// Usage: node scripts/fetch-schedule.mjs [seasonYear]
//   seasonYear is the year the season ENDS in (2027 = the 2026-27 season).

import { mkdirSync, writeFileSync } from "node:fs";

const SEASON = Number(process.argv[2] || process.env.SEASON || 2027);
const API_URL = `https://lm-api-reads.fantasy.espn.com/apis/v3/games/fba/seasons/${SEASON}?view=proTeamSchedules_wl`;

const res = await fetch(API_URL, {
  headers: { Accept: "application/json", "User-Agent": "Mozilla/5.0 (fantasy-cat-checker)" },
});
if (!res.ok) throw new Error(`ESPN schedule request failed (HTTP ${res.status})`);
const data = await res.json();

const proTeams = data.settings?.proTeams || [];
// ESPN's own abbreviations (NY, GS, SA, NO, UTAH, WSH) differ from the ones in data/players.js.
const RENAME = { NY: "NYK", GS: "GSW", SA: "SAS", NO: "NOP", UTAH: "UTA", WSH: "WAS" };
const abbrev = Object.fromEntries(
  proTeams.map((t) => {
    const a = (t.abbrev || "").toUpperCase();
    return [t.id, RENAME[a] || a];
  }),
);
// Game dates in US Eastern time, which is how NBA game days are counted.
const etDate = (ms) => new Date(ms).toLocaleDateString("en-CA", { timeZone: "America/New_York" });

const teams = {};
for (const t of proTeams) {
  if (!t.id) continue; // id 0 is free agents
  const games = new Map();
  for (const list of Object.values(t.proGamesByScoringPeriod || {})) {
    for (const g of list) {
      const home = g.homeProTeamId === t.id;
      games.set(g.id ?? `${g.date}`, {
        date: etDate(g.date),
        opp: (home ? "" : "@") + (abbrev[home ? g.awayProTeamId : g.homeProTeamId] || "?"),
      });
    }
  }
  teams[abbrev[t.id]] = [...games.values()].sort((a, b) => a.date.localeCompare(b.date));
}

const total = Object.values(teams).reduce((n, g) => n + g.length, 0);
if (Object.keys(teams).length < 30 || total < 500) {
  throw new Error(`Schedule looks incomplete (${Object.keys(teams).length} teams, ${total} games); not saving.`);
}

mkdirSync(new URL("../data/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../data/schedule.js", import.meta.url),
  `// Auto-generated by scripts/fetch-schedule.mjs - do not edit by hand.\n` +
    `window.SCHEDULE = ${JSON.stringify({ season: SEASON, updated: new Date().toISOString(), teams })};\n`,
);
console.log(`Saved schedules for ${Object.keys(teams).length} teams (${total} team-games).`);
