// Downloads every team's roster in our ESPN league and rewrites data/league.js
// (the other managers) and data/my-team.js (our team), so trades, adds and drops
// show up on the site without editing anything by hand. It also saves this week's
// live head-to-head category scores to data/matchup.js.
//
// Usage: node scripts/fetch-league.mjs
// Env:   LEAGUE_ID, MY_TEAM_ID, SEASON (year the season ends in, e.g. 2027)
//        ESPN_S2 and SWID only if the league is private (copy them from your
//        browser's espn.com cookies into the repository's Actions secrets).

import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const LEAGUE_ID = process.env.LEAGUE_ID || "1306956773";
const MY_TEAM_ID = Number(process.env.MY_TEAM_ID || 24);
const SEASON = Number(process.env.SEASON || 2027);
const { ESPN_S2, SWID } = process.env;

const API_URL =
  `https://lm-api-reads.fantasy.espn.com/apis/v3/games/fba/seasons/${SEASON}` +
  `/segments/0/leagues/${LEAGUE_ID}?view=mTeam&view=mRoster&view=mSettings&view=mMatchupScore&view=mScoreboard`;

const LEAGUE_FILE = new URL("../data/league.js", import.meta.url);
const MY_TEAM_FILE = new URL("../data/my-team.js", import.meta.url);
const MATCHUP_FILE = new URL("../data/matchup.js", import.meta.url);

// ESPN basketball stat ids for the categories a league can score.
const STAT_LABELS = {
  0: "PTS", 1: "BLK", 2: "STL", 3: "AST", 4: "OREB", 5: "DREB", 6: "REB", 11: "TO", 13: "FGM", 14: "FGA",
  15: "FTM", 16: "FTA", 17: "3PM", 18: "3PA", 19: "FG%", 20: "FT%", 21: "3P%", 35: "A/TO", 37: "DD", 38: "TD",
};

async function fetchLeague(tries = 4) {
  const headers = { Accept: "application/json", "User-Agent": "Mozilla/5.0 (fantasy-cat-checker)" };
  if (ESPN_S2 && SWID) headers.Cookie = `espn_s2=${ESPN_S2}; SWID=${SWID}`;
  let delay = 2000;
  for (let i = 1; ; i++) {
    const res = await fetch(API_URL, { headers }).catch((err) => ({ ok: false, status: 0, err }));
    if (res.ok) return res.json();
    if (res.status === 401 || res.status === 403) {
      throw new Error(
        `ESPN refused access to league ${LEAGUE_ID} (HTTP ${res.status}). The league is private: ` +
          (ESPN_S2 && SWID ? "the ESPN_S2/SWID secrets look expired, copy fresh ones." : "add the ESPN_S2 and SWID secrets."),
      );
    }
    if (i >= tries) throw new Error(`ESPN request failed (${res.status || res.err?.message})`);
    console.warn(`Attempt ${i} failed (${res.status || res.err?.message}); retrying in ${delay / 1000}s`);
    await new Promise((r) => setTimeout(r, delay));
    delay *= 2;
  }
}

// Load one of our data files (they assign to window.X) to compare with and keep notes from.
function loadDataFile(url, key) {
  try {
    const ctx = { window: {} };
    vm.runInNewContext(readFileSync(url, "utf8"), ctx);
    return ctx.window[key] || null;
  } catch {
    return null;
  }
}

const teamName = (t) => (t.name || `${t.location || ""} ${t.nickname || ""}`).trim() || `Team ${t.id}`;
const rosterOf = (t) =>
  (t.roster?.entries || []).map((e) => e.playerPoolEntry?.player?.fullName).filter(Boolean);

const data = await fetchLeague();
const teams = data.teams || [];
if (teams.length < 2) throw new Error(`ESPN returned ${teams.length} teams; not saving.`);
const mine = teams.find((t) => t.id === MY_TEAM_ID);
if (!mine) throw new Error(`Team ${MY_TEAM_ID} is not in league ${LEAGUE_ID}; check MY_TEAM_ID.`);
if (!teams.some((t) => rosterOf(t).length)) throw new Error("ESPN returned no rosters; not saving.");

const today = new Date().toISOString().slice(0, 10);
const stamp = `// Auto-generated by scripts/fetch-league.mjs from ESPN league ${LEAGUE_ID}. Edits here are overwritten.\n`;

// --- data/league.js: everyone except us ---
const opponents = teams
  .filter((t) => t.id !== MY_TEAM_ID)
  .map((t) => ({ name: teamName(t), players: rosterOf(t) }))
  .sort((a, b) => a.name.localeCompare(b.name));
const oldLeague = loadDataFile(LEAGUE_FILE, "LEAGUE");
const leagueSame =
  oldLeague &&
  oldLeague.myTeam === teamName(mine) &&
  JSON.stringify(oldLeague.teams) === JSON.stringify(opponents);
if (!leagueSame) {
  const league = { version: (oldLeague?.version || 0) + 1, updated: today, myTeam: teamName(mine), teams: opponents };
  writeFileSync(LEAGUE_FILE, `${stamp}window.LEAGUE = ${JSON.stringify(league, null, 2)};\n`);
}

// --- data/my-team.js: our roster, keeping the role/note written for players we still have ---
const oldMine = loadDataFile(MY_TEAM_FILE, "MY_TEAM");
const notes = Object.fromEntries((oldMine?.players || []).map((p) => [p.name, p]));
const lineup = Object.fromEntries((mine.roster?.entries || []).map((e) => [e.playerPoolEntry?.player?.fullName, e.lineupSlotId]));
const BENCH = 12, IR = 13; // ESPN basketball lineup slot ids
const myPlayers = rosterOf(mine).map((name) => {
  const slot = lineup[name];
  const role = slot === IR ? "IR" : slot === BENCH ? "Bench" : "Starter";
  return { name, role, note: notes[name]?.note || "" };
});
const mineSame =
  oldMine && JSON.stringify(oldMine.players.map((p) => [p.name, p.role])) === JSON.stringify(myPlayers.map((p) => [p.name, p.role]));
if (!mineSame) {
  const team = { version: (oldMine?.version || 0) + 1, updated: today, players: myPlayers };
  writeFileSync(
    MY_TEAM_FILE,
    `${stamp}// Notes are kept for players who stay on the team; edit them here or ask Claude.\nwindow.MY_TEAM = ${JSON.stringify(team, null, 2)};\n`,
  );
}

// --- data/matchup.js: this week's head-to-head score for our team ---
// Kept separate so a change in ESPN's scoreboard format never stops the roster sync.
let matchupNote = "matchup.js unchanged";
try {
  const week = currentMatchup(data, MY_TEAM_ID);
  const old = loadDataFile(MATCHUP_FILE, "MATCHUP");
  const strip = (m) => JSON.stringify({ ...m, updated: undefined });
  if (week && old && strip(old) === strip(week)) {
    matchupNote = `matchup.js unchanged (week ${week.week})`;
  } else if (week) {
    writeFileSync(
      MATCHUP_FILE,
      `${stamp}window.MATCHUP = ${JSON.stringify(week, null, 2)};\n`,
    );
    matchupNote = `matchup.js updated (week ${week.week}: ${week.score.wins}-${week.score.losses}-${week.score.ties} vs ${week.opponent})`;
  } else {
    matchupNote = "no current matchup found";
  }
} catch (err) {
  matchupNote = `matchup skipped (${err.message})`;
}

function currentMatchup(data, myId) {
  const week = data.status?.currentMatchupPeriod;
  const game = (data.schedule || []).find(
    (m) => m.matchupPeriodId === week && (m.home?.teamId === myId || m.away?.teamId === myId),
  );
  if (!game || !game.away) return null;
  const [us, them] = game.home.teamId === myId ? [game.home, game.away] : [game.away, game.home];
  const score = (side) => side.cumulativeScoreLive || side.cumulativeScore || {};
  const ours = score(us), theirs = score(them);
  const items = data.settings?.scoringSettings?.scoringItems || [];
  const ids = items.length ? items.map((i) => String(i.statId)) : Object.keys(ours.scoreByStat || {});
  const reverse = new Set(items.filter((i) => i.isReverseItem).map((i) => String(i.statId)));
  const cats = ids.map((id) => {
    const a = ours.scoreByStat?.[id], b = theirs.scoreByStat?.[id];
    return {
      label: STAT_LABELS[id] || `Stat ${id}`,
      mine: a?.score ?? null,
      theirs: b?.score ?? null,
      result: a?.result || null, // WIN / LOSS / TIE from ESPN, from our side
      lowerWins: reverse.has(id),
    };
  });
  const days = data.settings?.scheduleSettings?.matchupPeriods?.[week] || [];
  const dayIdx = days.indexOf(data.scoringPeriodId);
  return {
    updated: new Date().toISOString(),
    week,
    day: dayIdx >= 0 ? dayIdx + 1 : null,
    days: days.length || null,
    opponent: teamName((data.teams || []).find((t) => t.id === them.teamId) || { id: them.teamId }),
    score: { wins: ours.wins ?? 0, losses: ours.losses ?? 0, ties: ours.ties ?? 0 },
    cats,
  };
}

console.log(
  `League ${LEAGUE_ID}: ${teams.length} teams. ${teamName(mine)} has ${myPlayers.length} players. ` +
    `league.js ${leagueSame ? "unchanged" : "updated"}, my-team.js ${mineSame ? "unchanged" : "updated"}, ${matchupNote}.`,
);
