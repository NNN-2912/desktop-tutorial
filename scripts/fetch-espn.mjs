// Pulls player projections and season stats from ESPN's public fantasy basketball API
// and writes them to data/players.js for the web app.
//
// Usage: node scripts/fetch-espn.mjs [seasonYear]
//   seasonYear is the year the season ENDS in (2027 = the 2026-27 season).

import { writeFileSync } from "node:fs";

const SEASON = Number(process.argv[2] || process.env.SEASON || 2027);
const LIMIT = 550;

const API_URL = `https://lm-api-reads.fantasy.espn.com/apis/v3/games/fba/seasons/${SEASON}/segments/0/leaguedefaults/3?view=kona_player_info`;

// ESPN stat ids -> our keys
const STAT = {
  pts: "0", blk: "1", stl: "2", ast: "3", reb: "6", to: "11",
  fgm: "13", fga: "14", ftm: "15", fta: "16", tpm: "17", tpa: "18",
  min: "40", gp: "42",
};

const TEAMS = {
  0: "FA", 1: "ATL", 2: "BOS", 3: "NOP", 4: "CHI", 5: "CLE", 6: "DAL", 7: "DEN", 8: "DET",
  9: "GSW", 10: "HOU", 11: "IND", 12: "LAC", 13: "LAL", 14: "MIA", 15: "MIL", 16: "MIN",
  17: "BKN", 18: "NYK", 19: "ORL", 20: "PHI", 21: "PHX", 22: "POR", 23: "SAC", 24: "SAS",
  25: "OKC", 26: "UTA", 27: "WAS", 28: "TOR", 29: "MEM", 30: "CHA",
};

// ESPN lineup slot ids for the five real positions
const SLOT_POS = { 0: "PG", 1: "SG", 2: "SF", 3: "PF", 4: "C" };
const DEFAULT_POS = { 1: "PG", 2: "SG", 3: "SF", 4: "PF", 5: "C" };

const sources = {
  proj: `1${SEASON}`, // projected, full season
  season: `0${SEASON}`, // actual, season to date
  last: `0${SEASON - 1}`, // actual, last season
};

const filter = {
  players: {
    limit: LIMIT,
    sortPercOwned: { sortPriority: 1, sortAsc: false },
    filterStatsForTopScoringPeriodIds: {
      value: 2,
      additionalValue: [`00${SEASON}`, `10${SEASON}`, `00${SEASON - 1}`],
    },
  },
};

async function fetchWithRetry(tries = 4) {
  let delay = 2000;
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(API_URL, {
        headers: {
          "X-Fantasy-Filter": JSON.stringify(filter),
          "X-Fantasy-Platform": "kona-PROD",
          "X-Fantasy-Source": "kona",
          Accept: "application/json",
          "User-Agent": "Mozilla/5.0 (fantasy-cat-checker)",
        },
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (err) {
      if (i >= tries) throw err;
      console.warn(`Attempt ${i} failed (${err.message}); retrying in ${delay / 1000}s`);
      await new Promise((r) => setTimeout(r, delay));
      delay *= 2;
    }
  }
}

function pickStats(entry) {
  if (!entry) return null;
  const tot = entry.stats || {};
  const gp = tot[STAT.gp] || 0;
  if (!gp) return null;
  const out = { gp: Math.round(gp) };
  for (const [k, id] of Object.entries(STAT)) {
    if (k === "gp") continue;
    // store per-game averages, rounded to 2 dp
    out[k] = Math.round(((tot[id] || 0) / gp) * 100) / 100;
  }
  return out;
}

const json = await fetchWithRetry();
const list = Array.isArray(json) ? json : json.players || [];
if (!list.length) throw new Error("ESPN returned no players");

const players = [];
for (const row of list) {
  const p = row.player || row;
  if (!p || !p.fullName) continue;
  const byId = Object.fromEntries((p.stats || []).filter((s) => s.statSplitTypeId === 0).map((s) => [s.id, s]));
  const rec = {
    id: p.id,
    name: p.fullName,
    team: TEAMS[p.proTeamId] ?? "FA",
    pos: [...new Set((p.eligibleSlots || []).map((s) => SLOT_POS[s]).filter(Boolean))].join(",") ||
      DEFAULT_POS[p.defaultPositionId] || "",
    inj: p.injuryStatus && p.injuryStatus !== "ACTIVE" ? p.injuryStatus : "",
    own: Math.round((p.ownership?.percentOwned || 0) * 10) / 10,
    adp: Math.round((p.ownership?.averageDraftPosition || 0) * 10) / 10,
  };
  for (const [key, id] of Object.entries(sources)) {
    const s = pickStats(byId[id]);
    if (s) rec[key] = s;
  }
  if (rec.proj || rec.season || rec.last) players.push(rec);
}

const payload = {
  source: "ESPN Fantasy",
  season: `${SEASON - 1}-${String(SEASON).slice(2)}`,
  updated: new Date().toISOString(),
  players,
};

writeFileSync(
  new URL("../data/players.js", import.meta.url),
  `// Auto-generated by scripts/fetch-espn.mjs - do not edit by hand.\nwindow.PLAYER_DATA = ${JSON.stringify(payload)};\n`,
);
console.log(
  `Saved ${players.length} players (${players.filter((p) => p.proj).length} with projections, ` +
    `${players.filter((p) => p.season).length} with ${payload.season} stats).`,
);
